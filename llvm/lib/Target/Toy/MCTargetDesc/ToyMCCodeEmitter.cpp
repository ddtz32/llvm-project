#include "ToyMCTargetDesc.h"
#include "llvm/ADT/bit.h"
#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/Support/EndianStream.h"

using namespace llvm;

namespace {

class ToyMCCodeEmitter final : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  ToyMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx);

  void encodeInstruction(const MCInst &Inst, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // auto generated by tablegen
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  // ToyGenMCCodeEmitter.inc use this function to encode operand
  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  template <unsigned N>
  uint64_t getImmOpValueAsrN(const MCInst &MI, unsigned OpNo,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;
};

} // namespace

ToyMCCodeEmitter::ToyMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
    : MCII(MCII), Ctx(Ctx) {}

void ToyMCCodeEmitter::encodeInstruction(const MCInst &Inst,
                                         SmallVectorImpl<char> &CB,
                                         SmallVectorImpl<MCFixup> &Fixups,
                                         const MCSubtargetInfo &STI) const {

  const MCInstrDesc &Desc = MCII.get(Inst.getOpcode());
  assert(Desc.Size == 4 && "Size of toy instruction must be 4!");
  unsigned Bits = getBinaryCodeForInstr(Inst, Fixups, STI);
  support::endian::write(CB, Bits, llvm::endianness::little);
}

#include "ToyGenMCCodeEmitter.inc"

uint64_t ToyMCCodeEmitter::getMachineOpValue(const MCInst &MI,
                                             const MCOperand &MO,
                                             SmallVectorImpl<MCFixup> &Fixups,
                                             const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());

  if (MO.isImm())
    return MO.getImm();

  llvm_unreachable("Invalid MCOperand");
  return 0;
}

template <unsigned N>
uint64_t ToyMCCodeEmitter::getImmOpValueAsrN(const MCInst &MI, unsigned OpNo,
                                             SmallVectorImpl<MCFixup> &Fixups,
                                             const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  assert(MO.isImm());
  uint64_t Imm = MO.getImm();
  assert((Imm & ((1 << N) - 1)) == 0 && "LSB is noe-zero");
  return Imm >> N;
}

MCCodeEmitter *llvm::createToyMCCodeEmitter(const MCInstrInfo &MCII,
                                            MCContext &Ctx) {
  return new ToyMCCodeEmitter(MCII, Ctx);
}
